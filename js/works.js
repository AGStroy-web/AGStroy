// =========================================================
// RENDER WORKS
// =========================================================

function renderWorks() {

  if (!worksGrid || !pagination) {
    return;
  }


    const works = getCurrentWorks();

    console.log("Категория:", currentCategory);
    console.log("Количество фото:", works.length);
    console.log("Фото на странице:", perPage);


  const totalPages =
    Math.max(
      1,
      Math.ceil(
        works.length / perPage
      )
    );


  if (currentPage > totalPages) {
    currentPage = totalPages;
  }


  const start =
    (currentPage - 1) * perPage;


  const pageWorks =
    works.slice(
      start,
      start + perPage
    );


  // =======================================================
  // PHOTOS
  // =======================================================

  worksGrid.innerHTML =
    pageWorks
      .map((work, index) => {

        const photoNumber =
          start + index + 1;


        return `

          <article class="work-card">

            <button
              class="work-card__image"
              type="button"
              data-image="${work.image}"
              aria-label="${
                tr().openPhoto
              } ${photoNumber}"
            >

              <img
                src="${work.image}"
                alt="AGStroy — ${
                  tr().openPhoto
                } ${photoNumber}"
                loading="lazy"
              >

              <span
                class="work-card__zoom"
                aria-hidden="true"
              >
                ↗
              </span>

            </button>

          </article>

        `;

      })
      .join("");


  // =======================================================
  // PAGINATION
  // =======================================================

  const pages = [1];


  if (currentPage > 4) {
    pages.push("...");
  }


  for (
    let i =
      Math.max(
        2,
        currentPage - 2
      );

    i <=
      Math.min(
        totalPages - 1,
        currentPage + 2
      );

    i++
  ) {

    pages.push(i);

  }


  if (
    currentPage <
    totalPages - 3
  ) {

    pages.push("...");

  }


  if (
    totalPages > 1 &&
    !pages.includes(totalPages)
  ) {

    pages.push(totalPages);

  }


  pagination.innerHTML = `

    <button
      class="pagination__button"
      data-page="${currentPage - 1}"
      aria-label="${tr().prevPage}"
      ${currentPage === 1 ? "disabled" : ""}
    >
      ←
    </button>

    ${pages
      .map(page => {

        if (page === "...") {

          return `
            <span class="pagination__dots">
              ...
            </span>
          `;

        }


        return `

          <button
            class="pagination__button ${
              page === currentPage
                ? "is-active"
                : ""
            }"
            data-page="${page}"
          >
            ${page}
          </button>

        `;

      })
      .join("")}

    <button
      class="pagination__button"
      data-page="${currentPage + 1}"
      aria-label="${tr().nextPage}"
      ${
        currentPage === totalPages
          ? "disabled"
          : ""
      }
    >
      →
    </button>

  `;


  pagination
    .querySelectorAll(
      "button:not(:disabled)"
    )
    .forEach(button => {

      button.onclick = () => {

        currentPage =
          Number(
            button.dataset.page
          );


        renderWorks();


        document
          .querySelector("#works")
          ?.scrollIntoView({
            behavior: "smooth",
            block: "start"
          });

      };

    });

}


// =========================================================
// LIGHTBOX
// =========================================================

function setupLightbox() {

  if (!worksGrid) {
    return;
  }


  const lightbox =
    document.createElement("div");

  lightbox.className =
    "image-lightbox";


  lightbox.innerHTML = `

    <button
      class="image-lightbox__close"
      type="button"
      aria-label="${tr().close}"
    >
      ×
    </button>

    <img
      class="image-lightbox__image"
      src=""
      alt=""
    >

  `;


  document.body.appendChild(
    lightbox
  );


  const image =
    lightbox.querySelector(
      ".image-lightbox__image"
    );


  const closeButton =
    lightbox.querySelector(
      ".image-lightbox__close"
    );


  const close = () => {

    lightbox.classList.remove(
      "is-open"
    );

    document.body.classList.remove(
      "lightbox-open"
    );

    image.src = "";

  };


  worksGrid.addEventListener(
    "click",
    event => {

      const button =
        event.target.closest(
          ".work-card__image"
        );


      if (!button) {
        return;
      }


      image.src =
        button.dataset.image;


      image.alt =
        button.querySelector(
          "img"
        )?.alt || "";


      lightbox.classList.add(
        "is-open"
      );


      document.body.classList.add(
        "lightbox-open"
      );

    }
  );


  closeButton.onclick = close;


  lightbox.onclick = event => {

    if (
      event.target === lightbox
    ) {

      close();

    }

  };


  document.addEventListener(
    "keydown",
    event => {

      if (event.key === "Escape") {
        close();
      }

    }
  );

}


