let currentLang =
  localStorage.getItem("agstroy-language") || "ru";

const tr = () =>
  translations[currentLang] || translations.ru;


// =========================================================
// TRANSLATIONS
// =========================================================

function applyTranslations() {
  const lang = tr();

  document.documentElement.lang = lang.lang;
  document.title = lang.title;

  document
    .querySelectorAll("[data-i18n]")
    .forEach(el => {

      const key = el.dataset.i18n;

      if (lang[key] !== undefined) {
        el.innerHTML = lang[key];
      }

    });


  document
    .querySelectorAll("[data-i18n-aria-label]")
    .forEach(el => {

      const key = el.dataset.i18nAriaLabel;

      if (lang[key] !== undefined) {
        el.setAttribute(
          "aria-label",
          lang[key]
        );
      }

    });


  document
    .querySelectorAll(".language-button")
    .forEach(button => {

      button.classList.toggle(
        "is-active",
        button.dataset.lang === currentLang
      );

    });


  document
    .querySelectorAll(".service-card")
    .forEach((card, i) => {

      const title =
        card.querySelector("h3");

      const text =
        card.querySelector("p");

      if (
        title &&
        lang.serviceTitles?.[i]
      ) {
        title.textContent =
          lang.serviceTitles[i];
      }

      if (
        text &&
        lang.serviceTexts?.[i]
      ) {
        text.textContent =
          lang.serviceTexts[i];
      }

    });


  document
    .querySelectorAll(".process-card")
    .forEach((card, i) => {

      const title =
        card.querySelector("h3");

      const text =
        card.querySelector("p");

      if (
        title &&
        lang.processTitles?.[i]
      ) {
        title.textContent =
          lang.processTitles[i];
      }

      if (
        text &&
        lang.processTexts?.[i]
      ) {
        text.textContent =
          lang.processTexts[i];
      }

    });


  window.dispatchEvent(
    new Event("languagechange-agstroy")
  );
}


